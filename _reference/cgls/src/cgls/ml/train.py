"""Train the congestion classifier (Spark MLlib RandomForest) on synthetic traffic windows.

Run:  python -m cgls.ml.train

Each training row imitates what one 30-second streaming window would contain for one
segment: a handful of noisy GPS speeds, a few sensor readings and a few weather readings,
averaged. The label is the true congestion level (0..3) that generated them.

IMPORTANT (be honest in your report): the data is synthetic. With real city data you would
replace generate_dataset() by a loader for historical records - nothing else changes.
"""
from __future__ import annotations

import json
import os
import random
import sys

from cgls import config
from cgls import traffic_model as tm
from cgls.features import compute_features
from cgls.network import SEGMENTS


def _mean(xs):
    return sum(xs) / len(xs) if xs else None


def generate_dataset(n: int, seed: int = 7) -> list[dict]:
    rng = random.Random(seed)
    rows = []
    for _ in range(n):
        s = rng.choice(SEGMENTS)
        demand = rng.uniform(0.02, 1.0)
        rain = 0.0 if rng.random() < 0.6 else rng.uniform(0.5, 25.0)
        boost = rng.uniform(0.2, 0.5) if rng.random() < 0.08 else 0.0
        c = tm.congestion_index(demand, s["demand_bias"], rain, boost, rng)

        n_gps = 0 if rng.random() < 0.03 else rng.randint(1, 12)       # a window can be empty
        n_sensor = rng.randint(2, 6)                                    # 30 s / 5 s = 6 readings
        n_weather = rng.randint(1, 3)                                   # 30 s / 10 s = 3 readings
        speeds = [tm.sample_speed(s["free_flow_kmph"], c, rng) for _ in range(n_gps)]
        occ = [tm.sample_occupancy(c, rng) for _ in range(n_sensor)]
        cnt = [tm.sample_vehicle_count(s["lanes"], c, rng) for _ in range(n_sensor)]
        rn = [max(0.0, rain + rng.gauss(0, 0.2)) for _ in range(n_weather)]
        vis = [tm.sample_visibility(rain, rng) for _ in range(n_weather)]

        f = compute_features(_mean(speeds), s["free_flow_kmph"], _mean(occ), _mean(cnt),
                             s["lanes"], _mean(rn), _mean(vis))
        f["label"] = float(tm.level_from_score(c))
        rows.append(f)
    return rows


def train_and_save(spark, n_rows: int = 60000, model_dir: str = config.MODEL_DIR,
                   metrics_path: str = config.METRICS_PATH) -> dict:
    import pandas as pd
    from pyspark.ml import Pipeline
    from pyspark.ml.classification import RandomForestClassifier
    from pyspark.ml.evaluation import MulticlassClassificationEvaluator
    from pyspark.ml.feature import VectorAssembler

    print(f"[train] generating {n_rows} synthetic windows ...", flush=True)
    pdf = pd.DataFrame(generate_dataset(n_rows))
    df = spark.createDataFrame(pdf)
    train, test = df.randomSplit([0.8, 0.2], seed=11)

    assembler = VectorAssembler(inputCols=config.FEATURES, outputCol="features", handleInvalid="keep")
    rf = RandomForestClassifier(labelCol="label", featuresCol="features", numTrees=60, maxDepth=7, seed=5)
    print("[train] fitting RandomForest (60 trees, depth 7) ...", flush=True)
    model = Pipeline(stages=[assembler, rf]).fit(train)

    pred = model.transform(test).cache()
    acc = MulticlassClassificationEvaluator(labelCol="label", metricName="accuracy").evaluate(pred)
    f1 = MulticlassClassificationEvaluator(labelCol="label", metricName="f1").evaluate(pred)

    cm = {f"true_{int(r['label'])}": {} for r in pred.select("label").distinct().collect()}
    for r in pred.groupBy("label", "prediction").count().collect():
        cm[f"true_{int(r['label'])}"][f"pred_{int(r['prediction'])}"] = r["count"]

    # Baseline: guess the level from GPS speed alone (what a simple speed filter would do)
    test_pdf = test.toPandas()
    base_pred = ((1.0 - test_pdf["speed_ratio"]) / 0.8).clip(0, 1).map(tm.level_from_score)
    base_acc = float((base_pred == test_pdf["label"].astype(int)).mean())

    importances = dict(zip(config.FEATURES, [round(float(x), 4) for x in model.stages[-1].featureImportances.toArray()]))
    metrics = {
        "n_train": train.count(), "n_test": test.count(),
        "accuracy": round(acc, 4), "weighted_f1": round(f1, 4),
        "baseline_speed_only_accuracy": round(base_acc, 4),
        "feature_importances": importances,
        "confusion_matrix": cm,
        "note": "trained on synthetic data generated by cgls.traffic_model",
    }
    os.makedirs(os.path.dirname(metrics_path), exist_ok=True)
    model.write().overwrite().save(model_dir)
    with open(metrics_path, "w") as f:
        json.dump(metrics, f, indent=2)

    print("\n[train] ============ RESULTS ============")
    print(f"[train] accuracy (RandomForest, all sources) : {acc:.3f}")
    print(f"[train] weighted F1                          : {f1:.3f}")
    print(f"[train] baseline (GPS speed only, rule)      : {base_acc:.3f}")
    print(f"[train] feature importances                  : {importances}")
    print(f"[train] model saved to {model_dir}")
    print(f"[train] metrics saved to {metrics_path}\n", flush=True)
    return metrics


def main() -> int:
    from pyspark.sql import SparkSession

    spark = (SparkSession.builder.appName("cgls-train").master(os.getenv("SPARK_MASTER", "local[2]"))
             .config("spark.sql.shuffle.partitions", "4").config("spark.ui.showConsoleProgress", "false")
             .getOrCreate())
    spark.sparkContext.setLogLevel("WARN")
    train_and_save(spark)
    spark.stop()
    return 0


if __name__ == "__main__":
    sys.exit(main())
